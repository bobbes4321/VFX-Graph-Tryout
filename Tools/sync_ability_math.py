"""Generate HLSL from the deliberately small, pure AbilityGeometry math section.

Only the marked section is translated. Unsupported managed syntax fails loudly;
CPU-only interfaces stay outside it. --check compares tokens without modifying
assets, so formatting and comments do not create false mismatches.
"""

import argparse
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Assets/LineLab/Production/Runtime/AbilityGeometry.cs"
OUTPUT = ROOT / "Assets/LineLab/Production/Shaders/AbilityCommon.hlsl"
FUNCTIONS = (
    "Hash",
    "SampleRamp",
    "Envelope",
    "Strand",
    "Point",
    "Tint",
    "Width",
    "Decor",
)
HEADER = """// Generated by Tools/sync_ability_math.py. Edit AbilityGeometry.cs instead.
#ifndef ABILITY_COMMON_INCLUDED
#define ABILITY_COMMON_INCLUDED
#include "RecipeData.hlsl"

struct AbilityLine
{
    float4 start;
    float4 end;
    float4 color;
    float4 shape;
};

struct Adornment
{
    float3 Position;
    float3 X;
    float3 Y;
    float3 Color;
    float2 Size;
    float Alpha;
    float TextureIndex;
};

float3 normalizesafe(float3 value, float3 fallback)
{
    float squaredLength = dot(value, value);
    return squaredLength > 1e-10 ? value * rsqrt(squaredLength) : fallback;
}

"""


def generate_hlsl(source):
    markers = ("// BEGIN SHARED MATH", "// END SHARED MATH")
    if any(source.count(marker) != 1 for marker in markers):
        raise ValueError("Expected one BEGIN/END SHARED MATH pair")
    code = source.split(markers[0])[1].split(markers[1])[0]
    code = textwrap.dedent(code).strip()
    found = re.findall(r"public static \w+ (\w+)\(", code)
    if tuple(found) != FUNCTIONS:
        raise ValueError(f"Unexpected shared functions: {found}")
    clean = re.sub(r"//[^\n]*|/\*.*?\*/", "", code, flags=re.S)
    if re.search(
        r"\b(throw|try|catch|using|foreach|lock|class|string|object|var)\b|=>|\?\.",
        clean,
    ):
        raise ValueError("Managed or unsupported syntax inside shared math")
    if clean.count("{") != clean.count("}"):
        raise ValueError("Unbalanced shared function braces")
    for name in re.findall(r"\bmath\.(\w+)", clean):
        if name not in {
            "frac",
            "sin",
            "cos",
            "saturate",
            "floor",
            "ceil",
            "min",
            "max",
            "lerp",
            "smoothstep",
            "normalizesafe",
            "cross",
            "PI",
            "pow",
        }:
            raise ValueError(f"Unsupported math function: {name}")
    code = code.replace("public static ", "").replace("LineData", "AbilityLine")
    code = code.replace("NativeArray<float4>", "StructuredBuffer<float4>")
    code = re.sub(r"\bnew\s+(float[234]?)\b", r"\1", code)
    code = code.replace("math.PI", "3.14159265359").replace("math.", "")
    code = re.sub(r"(?<=\d)f\b", "", code)
    code = re.sub(r"\bd\s*=\s*default\s*;", "d = (Adornment)0;", code)
    for field in ("Start", "End", "Color", "Shape"):
        code = re.sub(r"\bl\." + field + r"\b", "l." + field.lower(), code)
    for function in FUNCTIONS:
        code = re.sub(r"\b" + function + r"\s*\(", "Ability" + function + "(", code)
    return (
        HEADER
        + code
        + '\n\n// Historical graph compatibility; authored graphs use explicit recipe arguments.\n#include "LegacyAbilityMath.hlsl"\n#endif\n'
    )


def significant_tokens(source):
    source = re.sub(r"//[^\n]*|/\*.*?\*/", "", source, flags=re.S)
    return re.findall(r"\w+|[^\s]", source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate_hlsl(SOURCE.read_text(encoding="utf-8-sig"))
    if args.check:
        if not OUTPUT.exists() or significant_tokens(generated) != significant_tokens(
            OUTPUT.read_text(encoding="utf-8-sig")
        ):
            raise SystemExit(
                "AbilityCommon.hlsl is stale. Run Tools/sync_ability_math.py."
            )
        print("AbilityCommon.hlsl matches the shared recipe math")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print("Generated AbilityCommon.hlsl")


if __name__ == "__main__":
    main()
