"""Translate the shared C# ability recipes into their matching HLSL functions.

This is a small translator for AbilityGeometry, not a general C# compiler. Keep
shared methods limited to the math supported by both languages. The CPU-only
Segment method marks the end of the translated section.
"""

import argparse
import re
import textwrap
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SOURCE_PATH = PROJECT_ROOT / "Assets/LineLab/Production/Runtime/AbilityGeometry.cs"
OUTPUT_PATH = PROJECT_ROOT / "Assets/LineLab/Production/Shaders/AbilityCommon.hlsl"
FUNCTION_NAMES = (
    "Hash",
    "Palette",
    "LayerCount",
    "Envelope",
    "Strand",
    "Point",
    "Tint",
    "Decor",
)

HEADER = """// Generated by Tools/sync_ability_math.py. Edit AbilityGeometry.cs instead.
#ifndef ABILITY_COMMON_INCLUDED
#define ABILITY_COMMON_INCLUDED

struct AbilityLine
{
    float4 start;
    float4 end;
    float4 color;
    float4 shape;
};

struct Adornment
{
    float3 Position;
    float3 X;
    float3 Y;
    float3 Color;
    float2 Size;
    float Alpha;
};

float3 normalizesafe(float3 v, float3 fallback)
{
    float q = dot(v, v);
    return q > 1e-10 ? v * rsqrt(q) : fallback;
}

"""


def generate_hlsl(source):
    start = re.search(r"^[ \t]*public\s+static\s+float\s+Hash\b", source, re.M)
    end = re.search(r"^[ \t]*// CPU-only segment", source, re.M)
    if start is None or end is None:
        raise ValueError(
            "Cannot find the shared geometry section in AbilityGeometry.cs"
        )

    code = textwrap.dedent(source[start.start() : end.start()])
    code = re.sub(r"\bpublic\s+static\s+", "", code)
    code = code.replace("LineData", "AbilityLine")
    code = re.sub(r"\bnew\s+(float[234]?)\b", r"\1", code)
    code = code.replace("math.PI", "3.14159265359").replace("math.", "")
    code = re.sub(r"(?<=\d)f\b", "", code)

    # Preserve the original GPU signatures, including unsigned particle indices.
    code = re.sub(r"\bint\s+layer\s*,\s*int\s+j\b", "uint layer, uint j", code)
    code = re.sub(r"\bint\s+strand\b", "uint strand", code)
    code = re.sub(r"\bd\s*=\s*default\s*;", "d = (Adornment)0;", code)
    for field in ("Start", "End", "Color", "Shape"):
        code = re.sub(r"\bl\s*\.\s*" + field + r"\b", "l." + field.lower(), code)
    for function in FUNCTION_NAMES:
        code = re.sub(r"\b" + function + r"\s*\(", "Ability" + function + "(", code)

    # HLSL needs return blocks. Expressions may span several formatted lines.
    code = re.sub(
        r"((?:float[234]?|int)\s+Ability\w+\([^)]*\))\s*=>\s*([^;]+);",
        lambda match: match[1]
        + "\n{\n"
        + textwrap.indent("return " + match[2] + ";", "    ")
        + "\n}",
        code,
        flags=re.S,
    )
    return HEADER + code.rstrip() + "\n\n#endif\n"


def significant_tokens(source):
    """Ignore comments and whitespace so ordinary HLSL formatting is allowed."""
    source = re.sub(r"//[^\n]*|/\*.*?\*/", "", source, flags=re.S)
    return re.findall(r"\w+|[^\s]", source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Check without writing the HLSL"
    )
    args = parser.parse_args()
    generated = generate_hlsl(SOURCE_PATH.read_text())
    if args.check:
        if significant_tokens(generated) != significant_tokens(OUTPUT_PATH.read_text()):
            raise SystemExit(
                "AbilityCommon.hlsl is out of sync. Run Tools/sync_ability_math.py."
            )
        print("AbilityCommon.hlsl matches AbilityGeometry.cs")
    else:
        OUTPUT_PATH.write_text(generated)
        print("Generated matching HLSL from AbilityGeometry.cs")


if __name__ == "__main__":
    main()
